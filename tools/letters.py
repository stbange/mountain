"""A five-by-seven original bitmap alphabet for the native trail overlay."""

from PIL import Image
from make_art import tga, ROOT

rows = {
    "A": "0e11111f111111",
    "B": "1e11111e11111e",
    "C": "0f10101010100f",
    "D": "1c12111111121c",
    "E": "1f10101e10101f",
    "F": "1f10101e101010",
    "G": "0f10101711110f",
    "H": "1111111f111111",
    "I": "0e04040404040e",
    "J": "0702020212120c",
    "K": "11121418141211",
    "L": "1010101010101f",
    "M": "111b1515111111",
    "N": "11191915131311",
    "O": "0e11111111110e",
    "P": "1e11111e101010",
    "Q": "0e11111115120d",
    "R": "1e11111e141211",
    "S": "0f10100e01011e",
    "T": "1f040404040404",
    "U": "1111111111110e",
    "V": "11111111110a04",
    "W": "11111115151b11",
    "X": "11110a040a1111",
    "Y": "11110a04040404",
    "Z": "1f01020408101f",
    "0": "0e11131519110e",
    "1": "040c040404040e",
    "2": "0e11010204081f",
    "3": "1e01010e01011e",
    "4": "02060a121f0202",
    "5": "1f10101e01011e",
    "6": "0608101e11110e",
    "7": "1f010204080808",
    "8": "0e11110e11110e",
    "9": "0e11110f01020c",
    ":": "00040400040400",
    "/": "01020204080810",
    "?": "0e110102040004",
    "-": "0000000e000000",
    ".": "00000000000404",
    ",": "00000000000408",
    "+": "0004041f040400",
    " ": "00000000000000",
}
im = Image.new("RGBA", (16 * 6, 8 * 8))
for ch in range(128):
    s = rows.get(chr(ch).upper(), rows[" "])
    ox = ch % 16 * 6
    oy = ch // 16 * 8
    for y, mask in enumerate(bytes.fromhex(s)):
        for x in range(5):
            if mask & (1 << (4 - x)):
                im.putpixel((ox + x, oy + y), (255, 255, 255, 255))
tga(im, ROOT / "art" / "letters.tga")
